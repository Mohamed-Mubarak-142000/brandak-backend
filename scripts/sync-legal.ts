/**
 * Copies the legal texts from the app (the single source) into the API, which serves them as
 * public web pages for Google Play: `npx tsx scripts/sync-legal.ts` after editing them.
 */
import { writeFileSync } from 'fs';
import { join } from 'path';
import { LEGAL_UPDATED, PRIVACY, SUPPORT_EMAIL, TERMS } from '../../brandak app/src/features/info/content';

const data = { updated: LEGAL_UPDATED, supportEmail: SUPPORT_EMAIL, terms: TERMS, privacy: PRIVACY };
writeFileSync(
  join(__dirname, '../src/legal/legal-content.ts'),
  `// Generated by scripts/sync-legal.ts from the app's features/info/content.ts. Don't edit by hand.\nexport const LEGAL = ${JSON.stringify(data, null, 2)} as const;\n`,
);
console.log('legal-content.ts updated');
